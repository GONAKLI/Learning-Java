package ReverseList_93;

import java.util.Arrays;
import java.util.List;

public class ReversedList_93 {
    static void main() {
        List<Integer> courses = Arrays.asList(1,2,3,4,5,6,7,8,9);
        System.out.println("current list elements: " + courses);
        System.out.println("Reversed list elements: " + courses.reversed());

    }
}
